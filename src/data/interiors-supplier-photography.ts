export function verifiedSupplierImage(item: {supplier?:string;range?:string;slot?:string;finish?:string}, scheme?:string): SupplierProductImage | undefined {
  if (item.supplier==='Sto' && /exterior render/i.test(item.slot||'') && /9003|signal white/i.test(item.finish||'')) return supplierProductImages['STO-STOLIT-K-RAL9003'];
  if (item.supplier==='Dominó' && ['Floor tile','Wall tile'].includes(item.slot||'')) {
    const key='DOMINO-'+(item.range||'').toUpperCase().replace('CRYSTAL','CRISTAL').replace(/ /g,'-')+'-CAT';
    const hit=(supplierProductImages as Record<string,SupplierProductImage>)[key];
    if(hit) return hit;
  }
  if (item.supplier==='Compincar' && ['Interior doors','Interior door'].includes(item.slot||'')) {
    if (/^Lisa$/i.test(item.range||'')) return supplierProductImages['COMPINCAR-LISA-CAT'];
    if (/^Model 301$/i.test(item.range||'')) return supplierProductImages['COMPINCAR-301-CAT'];
    if (/^Model 302$/i.test(item.range||'')) return supplierProductImages['COMPINCAR-302-CAT'];
  }

  if (item.supplier==='Cortizo' && ['Window and exterior door frames','Windows and exterior doors','Window Frames'].includes(item.slot||'')) {
    if (/anthracite/i.test(item.finish||'')) return supplierProductImages['CORTIZO-ANTHRACITE-APPROVED-BOARD'];
    if (/white|9010/i.test(item.finish||'')) return supplierProductImages['CORTIZO-WHITE-APPROVED-BOARD'];
  }

  if (item.supplier==='Elleci'&&item.range==='Quadra 130'&&item.slot==='Kitchen sink'&&scheme) {
    const choice: Record<string, keyof typeof supplierProductImages> = {
      'coastal/natural':'ELLECI-Q130-G62',
      'coastal/ocean':'ELLECI-Q130-K88',
      'coastal/refined':'ELLECI-Q130-K89',
      'contemporary/pure':'ELLECI-Q130-K96',
      'contemporary/graphite':'ELLECI-Q130-K86',
      'contemporary/mineral':'ELLECI-Q130-K89',
      'signature/atelier':'ELLECI-Q130-G43',
      'signature/gallery':'ELLECI-Q130-K95',
      'signature/noir':'ELLECI-Q130-K86',
      'tropical/canopy':'ELLECI-Q130-G51',
      'tropical/lagoon':'ELLECI-Q130-K88',
      'tropical/terracotta':'ELLECI-Q130-G62'
    };
    const key=choice[scheme];return key?supplierProductImages[key]:undefined;
  }
  if (item.supplier==='Compincar' && ['Interior doors','Interior door'].includes(item.slot||'')) {
    if (/^Lisa$/i.test(item.range||'')) return supplierProductImages['COMPINCAR-LISA-RW163'];
    if (/^Model 301$/i.test(item.range||'')) return supplierProductImages['COMPINCAR-301-MAPLE'];
  }

  if (item.supplier==='Bruma'&&item.range==='Ginger'&&item.slot==='Kitchen faucet' && /chrome/i.test(item.finish||'')) return supplierProductImages['BRUMA-GINGER-1227003CR'];
  if (item.supplier==='Bruma'&&item.range==='Breeze'&&item.slot==='Basin faucet' && /chrome/i.test(item.finish||'')) return supplierProductImages['BRUMA-BREEZE-1680000CR'];
  if (item.supplier==='Bruma'&&item.range==='Nautic'&&item.slot==='Basin faucet' && /chrome/i.test(item.finish||'')) return supplierProductImages['BRUMA-NAUTIC-1810101CR'];
  if (item.supplier==='Bruma'&&item.range==='Avalon'&&item.slot==='Basin faucet' && /chrome/i.test(item.finish||'')) return supplierProductImages['BRUMA-AVALON-1890101CR'];
  if (['signature/gallery','coastal/natural'].includes(scheme||'')&&item.supplier==='Nobilia'&&item.slot==='Countertop') return supplierProductImages['NOBILIA-WORKTOP-376'];
  if (item.supplier==='Nobilia'&&item.slot==='Kitchen front'&&scheme&&chosenFronts[scheme]){
    const p=supplierProductImages[chosenFronts[scheme]];
    return p.range.toLowerCase()===item.range?.toLowerCase()?p:undefined;
  }
  return undefined;
}

